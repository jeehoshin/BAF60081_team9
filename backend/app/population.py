def district_population(city: str | None, gu: str | None) -> int | None:
    """구 인구. 도시('서울'/'대전')와 구('OO구')를 같이 받아야 한다. 모르면 None."""
    if not city or not gu:
        return None
    return DISTRICTS.get(_ALIASES.get(city.strip(), city.strip()), {}).get(gu.strip())


def population_of(label: str | None) -> int | None:
    """시·도 이름(약칭·정식 이름 모두)으로 인구를 찾는다. 모르면 None."""
    if not label:
        return None
    name = label.strip()
    if name in _MERGED:
        return sum(POPULATION[part] for part in _MERGED[name])
    return POPULATION.get(_ALIASES.get(name, name))


def per_100k(value: float | int | None, population: int | None) -> float | None:
    """인구 10만 명당 값 (소수 첫째 자리)."""
    if value is None or not population:
        return None
    return round(value / population * 100_000, 1)
